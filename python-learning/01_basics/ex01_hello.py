# Exercise 01 - Hello World & Variables
# -----------------------------------------
# GOAL: Print text to the screen and store values in variables.
#
# CONCEPTS:
#   print()    - outputs text to the terminal
#   Variables  - named containers that store values
#   str        - text (wrapped in quotes)
#   int        - whole numbers
#   float      - decimal numbers
#   bool       - True or False
#
# ------ YOUR PLAYGROUND BELOW -----

# 1. Print a greeting
print("Hello, World!")

# 2. Store your name in a variable and greet yourself
name = "Ajay"
print("Hello,", name)

# 3. Variables can hold numbers too
age = 25
height = 1.75          # metres
is_student = True
city = "Houston"

print("Age:", age)
print("Height:", height)
print("Is a student?", is_student)
print("City:", city)

# 4. You can do basic math inline
print("Double my age:", age * 2)

